var wasmImportCmd = &cobra.Command{
	Use:   "import [file.wasm]",
	Short: "Import a Wasm module to the Mixer catalog",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		allowUnsigned, _ := cmd.Flags().GetBool("allow-unsigned")
		filePath := args[0]

		f, err := os.Open(filePath)
		if err != nil {
			return err
		}
		defer func() { _ = f.Close() }()

		wasmBytes, err := io.ReadAll(f)
		if err != nil {
			return err
		}

		url := fmt.Sprintf("http://localhost:8090/api/v1/wasm/import?allow_unsigned=%t", allowUnsigned)
		req, err := http.NewRequest("POST", url, bytes.NewReader(wasmBytes))
		if err != nil {
			return err
		}
		req.Header.Set("Content-Type", "application/octet-stream")

		client := &http.Client{}
		resp, err := client.Do(req)
		if err != nil {
			return err
		}
		defer func() { _ = resp.Body.Close() }()

		if resp.StatusCode != http.StatusOK {
			body, _ := io.ReadAll(resp.Body)
			return fmt.Errorf("import failed: %s - %s", resp.Status, string(body))
		}

		var result map[string]interface{}
		if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
			return err
		}

		fmt.Printf("Successfully imported Wasm module.\nHash: %s\nStatus: %s\n", result["hash"], result["status"])
		return nil
	},
}

var wasmSignCmd = &cobra.Command{
	Use:   "sign [file.wasm] [private_key.flux]",
	Short: "Embed a Vendor signature into a Wasm module",
	Args:  cobra.ExactArgs(2),
	RunE: func(cmd *cobra.Command, args []string) error {
		filePath := args[0]
		keyPath := args[1]

		// 1. Load the Wasm
		wasmBytes, err := os.ReadFile(filePath)
		if err != nil {
			return fmt.Errorf("failed to read wasm: %w", err)
		}

		// 2. Extract existing vendor signature if present
		_, stripped, errExt := catalog.ExtractCustomSection(wasmBytes, "fluxrig.signature")
		if errExt == nil {
			wasmBytes = stripped
		}

		// 3. Load Key
		env, err := pki.LoadStateEnvelope(keyPath)
		var privKey ed25519.PrivateKey
		if err != nil {
			// If not a state envelope, maybe a direct ed25519 private key?
			// We only officially support ClusterKey structure for vendor keys.
			clusterKey, errKey := pki.LoadClusterKey(keyPath)
			if errKey != nil {
				return fmt.Errorf("failed to load private key: %w", errKey)
			}
			privKey = clusterKey.Private
		} else {
			// Extracted from envelope? Envelopes don't contain private keys.
			// Assume it's a ClusterKey file.
			_ = env
			return fmt.Errorf("use a cluster.key generated by fluxrig pki init")
		}

		// 4. Sign
		hash := catalog.HashWasm(wasmBytes)
		sig := ed25519.Sign(privKey, hash)

		// 5. Append Custom Section
		signedWasm, err := catalog.AppendCustomSection(wasmBytes, "fluxrig.signature", sig)
		if err != nil {
			return fmt.Errorf("failed to append signature: %w", err)
		}

		if err := os.WriteFile(filePath, signedWasm, 0644); err != nil {
			return fmt.Errorf("failed to write signed wasm: %w", err)
		}

		fmt.Printf("Successfully signed %s with fluxrig.signature.\n", filePath)
		return nil
	},
}

var wasmListCmd = &cobra.Command{
	Use:   "list",
	Short: "List Wasm modules in the Mixer catalog",
	RunE: func(cmd *cobra.Command, args []string) error {
		apiURL, _ := cmd.Flags().GetString("api-url")
		req, err := newAPIRequest(cmd, http.MethodGet, apiURL+"/api/v1/wasm/catalog", nil)
		if err != nil {
			return err
		}
		resp, err := http.DefaultClient.Do(req)
		if err != nil {
			return err
		}
		defer func() { _ = resp.Body.Close() }()

		if resp.StatusCode != http.StatusOK {
			return fmt.Errorf("failed to get catalog: %s", resp.Status)
		}

		var list []map[string]interface{}
		if err := json.NewDecoder(resp.Body).Decode(&list); err != nil {
			return err
		}

		for _, item := range list {
			fmt.Printf("- Hash: %s\n  Status: %s\n  Size: %.2f KB\n\n", item["hash"], item["status"], float64(item["size_bytes"].(float64))/1024.0)
		}
		return nil
	},
}

var wasmKeysCmd = &cobra.Command{
	Use:   "keys",
	Short: "Manage the vendors every Mixer trusts",
	Long: `The trusted vendor keys are one keyring on the bus, shared by every Mixer:
a vendor trusted or revoked through one Mixer is trusted or refused by all.
A revoked vendor stays in the keyring as revoked, so a key file a Mixer still
holds in wasm.trusted_keys_dir does not add it back.`,
}

// wasmKeysRequest sends a keyring request to the Mixer and checks its status.
func wasmKeysRequest(cmd *cobra.Command, method, path string, body io.Reader, want int) ([]byte, error) {
	apiURL, _ := cmd.Flags().GetString("api-url")
	req, err := newAPIRequest(cmd, method, apiURL+"/api/v1/wasm/keys"+path, body)
	if err != nil {
		return nil, err
	}
	if body != nil {
		req.Header.Set("Content-Type", "application/octet-stream")
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	out, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != want {
		return nil, fmt.Errorf("%s: %s", resp.Status, bytes.TrimSpace(out))
	}
	return out, nil
}

var wasmKeysListCmd = &cobra.Command{
	Use:   "list",
	Short: "List the vendors of the keyring",
	RunE: func(cmd *cobra.Command, _ []string) error {
		out, err := wasmKeysRequest(cmd, http.MethodGet, "", nil, http.StatusOK)
		if err != nil {
			return err
		}
		var keys []catalog.TrustedKey
		if err = json.Unmarshal(out, &keys); err != nil {
			return err
		}
		for _, k := range keys {
			if k.Revoked {
				fmt.Printf("- %s: revoked\n", k.Vendor)
			} else {
				fmt.Printf("- %s: %s\n", k.Vendor, k.Fingerprint)
			}
		}
		return nil
	},
}

var wasmKeysTrustCmd = &cobra.Command{
	Use:   "trust [vendor] [key-file]",
	Short: "Trust a vendor's public key on every Mixer",
	Long: `The key file is the vendor's Ed25519 public key, 32 raw bytes in a file
named <name>.pub, or the key file the vendor signs with (fluxrig wasm sign),
whose public half is taken.`,
	Args: cobra.ExactArgs(2),
	RunE: func(cmd *cobra.Command, args []string) error {
		pub, err := trustedPublicKey(args[1])
		if err != nil {
			return err
		}
		if _, err = wasmKeysRequest(cmd, http.MethodPut, "/"+args[0], bytes.NewReader(pub), http.StatusNoContent); err != nil {
			return err
		}
		fmt.Printf("Every Mixer trusts %s.\n", args[0])
		return nil
	},
}

// trustedPublicKey reads the public key to trust from path. 32 raw bytes are
// a public key only in a .pub file: wasm sign also takes 32 bytes, as a
// private seed, and trusting such a file would send the private key to the
// Mixer, and trust a key no module is signed with.
func trustedPublicKey(path string) (ed25519.PublicKey, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if len(data) == ed25519.PublicKeySize {
		if !strings.HasSuffix(path, ".pub") {
			return nil, fmt.Errorf("%s has 32 bytes, which can be a private seed: name a public key file <name>.pub, or give the signing key file", path)
		}
		return ed25519.PublicKey(data), nil
	}
	key, err := pki.LoadClusterKey(path)
	if err != nil {
		return nil, fmt.Errorf("%s is neither a 32-byte public key nor a signing key file: %w", path, err)
	}
	return key.Public, nil
}

var wasmKeysRevokeCmd = &cobra.Command{
	Use:   "revoke [vendor]",
	Short: "Stop trusting a vendor on every Mixer",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		if _, err := wasmKeysRequest(cmd, http.MethodDelete, "/"+args[0], nil, http.StatusNoContent); err != nil {
			return err
		}
		fmt.Printf("No Mixer trusts %s.\n", args[0])
		return nil
	},
}

